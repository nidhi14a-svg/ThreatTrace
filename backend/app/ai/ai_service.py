"""
AI service boundary for sanitized finding explanations and remediation.

Enforces strict data minimization: external LLM providers receive only
pre-sanitized, bounded finding-level metadata, never entire source repositories,
raw source code files, or unredacted credentials.
"""

import re
from typing import Any, Literal

from pydantic import BaseModel, Field, field_validator

from app.scanners.base_scanner import BaseScanner

SeverityLiteral = Literal["critical", "high", "medium", "low"]
ConfidenceLiteral = Literal["high", "medium", "low"]


class AIFindingContext(BaseModel):
    """
    Sanitized, bounded finding context passed to Dev B's AI service.

    Guarantees that no repository files, unredacted secrets, or excessive
    code blocks are transmitted to external LLM providers.
    """

    finding_id: str = Field(
        ...,
        min_length=1,
        description="Unique identifier of the finding being analyzed.",
    )
    rule_id: str = Field(
        ...,
        min_length=1,
        description="Scanner rule or advisory identifier (e.g., 'bandit.B608', 'GHSA-...').",
    )
    domain: str = Field(
        ...,
        min_length=1,
        description="Canonical cybersecurity domain (e.g., 'Web Application Security').",
    )
    title: str = Field(
        ...,
        min_length=1,
        max_length=200,
        description="Short vulnerability summary.",
    )
    severity: SeverityLiteral = Field(
        ...,
        description="Normalized severity tier: critical, high, medium, or low.",
    )
    file: str = Field(
        ...,
        min_length=1,
        description="Workspace-relative POSIX file path.",
    )
    line: int | None = Field(
        default=None,
        ge=1,
        description="1-indexed line number if identified, or None for file/manifest-level findings.",
    )
    evidence: str = Field(
        ...,
        max_length=1000,
        description="Sanitized and bounded code snippet or advisory statement.",
    )
    confidence: ConfidenceLiteral = Field(
        ...,
        description="Confidence level: high, medium, or low.",
    )

    @field_validator("evidence")
    @classmethod
    def validate_evidence_safety(cls, v: str) -> str:
        """Assert evidence length does not exceed limit and contains zero unmasked credentials."""
        if len(v) > 1000:
            raise ValueError(f"Evidence exceeds maximum allowed AI context length of 1,000 characters (got {len(v)}).")

        # Check for unmasked AWS access keys
        if re.search(r"\bAKIA[0-9A-Z]{16}\b", v):
            raise ValueError("Unredacted AWS access key detected in AI evidence context.")

        # Check for unmasked GitHub PATs
        if re.search(r"\bgh[pousr]_[0-9a-zA-Z]{36}\b", v):
            raise ValueError("Unredacted GitHub personal access token detected in AI evidence context.")

        # Check for unmasked private keys
        if "-----BEGIN " in v and "PRIVATE KEY-----" in v:
            raise ValueError("Unredacted private key block detected in AI evidence context.")

        return v


class AIEnrichmentResult(BaseModel):
    """
    Additive enrichment generated by the AI service for a security finding.

    Strictly additive: cannot modify or overwrite verified scanner evidence,
    severity, rule ID, or file location.
    """

    finding_id: str = Field(
        ...,
        description="Identifier of the enriched finding.",
    )
    explanation: str | None = Field(
        default=None,
        description="AI-generated technical explanation of the vulnerability and exploit scenario.",
    )
    recommendation: str | None = Field(
        default=None,
        description="AI-generated actionable remediation guidance.",
    )


def create_ai_finding_context(
    finding_dict: dict[str, Any],
    finding_id: str | None = None,
) -> AIFindingContext:
    """
    Extract and sanitize only allowed fields from a finding dictionary into AIFindingContext.

    Strips any extraneous repository content, full source files, or unvetted metadata.
    Applies in-memory credential redaction and evidence bounding before instantiation.
    """
    fid = finding_id or finding_dict.get("id") or finding_dict.get("finding_id") or "find_unknown"
    raw_evidence = finding_dict.get("evidence") or ""

    # Apply mandatory redaction and bounding
    sanitized_evidence = BaseScanner.redact_evidence(raw_evidence)
    bounded_evidence = BaseScanner.bound_evidence(sanitized_evidence, max_chars=1000)

    # Normalize severity
    raw_sev = str(finding_dict.get("severity") or "medium").lower()
    sev: SeverityLiteral = "medium"
    if raw_sev in ("critical", "high", "medium", "low"):
        sev = raw_sev  # type: ignore

    # Normalize confidence
    raw_conf = str(finding_dict.get("confidence") or "medium").lower()
    conf: ConfidenceLiteral = "medium"
    if raw_conf in ("high", "medium", "low"):
        conf = raw_conf  # type: ignore

    # Normalize line
    line_val = finding_dict.get("line")
    line_num: int | None = None
    if isinstance(line_val, int) and line_val >= 1:
        line_num = line_val

    # Normalize domain
    domain_val = str(finding_dict.get("domain") or "General Security")

    # Normalize rule_id and title
    rule_id_val = str(
        finding_dict.get("rule_id")
        or finding_dict.get("check_id")
        or finding_dict.get("test_id")
        or "rule_unknown"
    )
    title_val = str(finding_dict.get("title") or finding_dict.get("message") or rule_id_val)[:200]
    file_val = str(finding_dict.get("file") or finding_dict.get("path") or "[UNKNOWN_FILE]")

    return AIFindingContext(
        finding_id=fid,
        rule_id=rule_id_val,
        domain=domain_val,
        title=title_val,
        severity=sev,
        file=file_val,
        line=line_num,
        evidence=bounded_evidence,
        confidence=conf,
    )


class AIService:
    """
    Boundary interface for the AI explanation and remediation service.

    Managed and implemented by Dev B for LLM provider invocation.
    Guarantees that external AI APIs only receive sanitized AIFindingContext.
    """

    def prepare_context(
        self,
        finding_dict: dict[str, Any],
        finding_id: str | None = None,
    ) -> AIFindingContext:
        """Construct sanitized AIFindingContext from finding data."""
        return create_ai_finding_context(finding_dict, finding_id=finding_id)

    def validate_context(self, context: AIFindingContext) -> bool:
        """Validate that context meets all safety and bounding invariants."""
        return bool(
            context.finding_id
            and context.rule_id
            and len(context.evidence) <= 1000
        )

    async def enrich_finding(
        self,
        context: AIFindingContext,
    ) -> AIEnrichmentResult:
        """
        Enrich a security finding with AI-assisted explanation and recommendation.

        Stub implementation for Phase 2: provides deterministic, safe fallback
        metadata. Dev B will hook up live Gemini or OpenAI provider calls in Phase 6.

        Args:
            context: Validated, sanitized finding context.

        Returns:
            AIEnrichmentResult: Additive explanation and recommendation.
        """
        # Validate boundary before dispatch
        self.validate_context(context)

        # Baseline rule-based fallback guidance
        fallback_explanation = (
            f"This finding represents a potential {context.severity} severity issue "
            f"in {context.domain} related to {context.rule_id}. "
            f"Review the evidence context in {context.file} to verify exploitability."
        )
        fallback_recommendation = (
            f"Apply secure coding standards for {context.rule_id}. "
            "Validate all inputs, sanitize untrusted parameters, and enforce strict least-privilege controls."
        )

        return AIEnrichmentResult(
            finding_id=context.finding_id,
            explanation=fallback_explanation,
            recommendation=fallback_recommendation,
        )
